def item_key(p):
    pf, v, n, fp = prefix(p), p['value'], p['note'], p['fp']
    if pf == 'R': return 'R:%s%s' % (v, ':1/2W' if 'DIN0414' in fp else '')
    if pf == 'C':
        k = 'C:' + v
        if 'NP0' in n or 'C0G' in n: k += ':NP0'
        if '500V' in n: k += ':500V'
        if '積層' in n: k += ':積層'
        return k
    if pf == 'L' and not v.endswith('uH'): return 'L:' + v.split()[0]
    if pf == 'T': return 'T:' + v.split()[0]
    if pf == 'J': return 'J:wire' if 'SolderWire' in fp else 'J:header'
    if pf == 'TP': return 'TP:'
    return '%s:%s' % (pf, v)


def buy_of(p):
    k = item_key(p)
    if k not in BUY: raise SystemExit('購入先が決まっていない部品: %s（%s）→ BUY に追加する' % (p['ref'], k))
    return BUY[k]


SECTION = {'R': '抵抗', 'VR': '半固定抵抗', 'TC': 'トリマコンデンサ', 'L': 'コイル', 'T': 'トランス', 'D': 'ダイオード',
           'Q': 'トランジスタ・FET', 'U': 'IC・レギュレータ・モジュール', 'X': '水晶・フィルタ', 'FL': '水晶・フィルタ',
           'K': 'リレー', 'J': 'コネクタ', 'TP': 'テストポイント'}
ORDER = ['抵抗', '半固定抵抗', 'コンデンサ（セラミック）', 'コンデンサ（電解）', 'トリマコンデンサ', 'コイル', 'トランス', 'ダイオード',
         'トランジスタ・FET', 'IC・レギュレータ・モジュール', '水晶・フィルタ', 'リレー', 'コネクタ', 'テストポイント']


def refkey(r):
    m = re.match(r'([A-Z]+)(\d+)', r); return (m.group(1), int(m.group(2)))


def rows():
    g = collections.OrderedDict()
    for p in sorted([p for p in parts if not p['ref'].startswith('#')], key=lambda p: refkey(p['ref'])):
        pf = prefix(p)
        sec = ('コンデンサ（電解）' if 'CP_Radial' in p['fp'] else 'コンデンサ（セラミック）') if pf == 'C' else SECTION[pf]
        g.setdefault((sec, item_key(p), p['value']), []).append(p)
    out = []
    for (sec, k, v), ps in g.items():
        name, b = buy_of(ps[0])
        out.append([sec, ','.join(p['ref'] for p in ps), name, v, ps[0]['fp'].split(':')[-1], len(ps), *b])
    out.sort(key=lambda r: (ORDER.index(r[0]), refkey(r[1].split(',')[0])))
    return out


